import type { Household, Person } from "../types";
import { maskCccd } from "../utils/cccd";
import { calculateAge, formatDobDisplay } from "../utils/date";
import { normalizeUnaccented, splitFullName } from "../utils/vietnamese";
import { VILLAGES } from "./constants";

function createMember(data: {
	id: string;
	household_id: string;
	stt: number;
	full_name: string;
	relationship: any;
	is_head: boolean;
	gender: "Nam" | "Nữ";
	dob_raw: string;
	cccd: string;
	ethnicity: string;
	religion: string;
	occupation?: string;
	notes?: string;
}): Person {
	const { lastName, firstName } = splitFullName(data.full_name);
	const age = calculateAge(data.dob_raw, 2026);
	const is_minority = data.ethnicity !== "Kinh";
	const cccd_last4 = data.cccd ? data.cccd.slice(-4) : "";

	return {
		...data,
		dob: data.dob_raw,
		last_name: lastName,
		first_name: firstName,
		name_unaccented: normalizeUnaccented(data.full_name),
		dob_formatted: formatDobDisplay(data.dob_raw),
		birth_year: 2026 - age,
		age,
		cccd_last4,
		cccd_masked: maskCccd(data.cccd, false),
		is_minority,
	};
}

